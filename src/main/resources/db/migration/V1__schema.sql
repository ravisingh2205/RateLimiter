-- Portable between PostgreSQL and H2 (PostgreSQL mode).

-- Catalogue of APIs: maps (method, path pattern) -> api_id used by the rules.
CREATE TABLE api_endpoint (
    api_id       VARCHAR(64)  PRIMARY KEY,
    http_method  VARCHAR(10)  NOT NULL,           -- GET, POST, ... or * for any
    path_pattern VARCHAR(255) NOT NULL,           -- /api/employees, /api/employees/{id}, /api/**
    description  VARCHAR(500)
);

-- Commercial / usage tiers.
CREATE TABLE rate_limit_plan (
    plan_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(64) NOT NULL UNIQUE,
    description VARCHAR(255)
);

-- The rules. api_id '*' = all APIs. plan_id NULL = default rule for everybody not on a plan that has its own rule.
CREATE TABLE rate_limit_rule (
    rule_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    api_id         VARCHAR(64) NOT NULL,
    plan_id        BIGINT REFERENCES rate_limit_plan(plan_id),
    dimension      VARCHAR(16) NOT NULL,          -- IP | EMP | DEPT | API_KEY | GLOBAL
    algorithm      VARCHAR(24) NOT NULL,          -- TOKEN_BUCKET | FIXED_WINDOW | SLIDING_WINDOW | LEAKY_BUCKET | CONCURRENCY
    limit_count    INT         NOT NULL,
    window_seconds INT         NOT NULL,
    burst_capacity INT,
    priority       INT         NOT NULL DEFAULT 100,
    fail_mode      VARCHAR(12) NOT NULL DEFAULT 'FAIL_OPEN',   -- FAIL_OPEN | FAIL_CLOSED
    mode           VARCHAR(10) NOT NULL DEFAULT 'ENFORCE',     -- ENFORCE | SHADOW
    enabled        BOOLEAN     NOT NULL DEFAULT TRUE,
    version        INT         NOT NULL DEFAULT 1,
    updated_by     VARCHAR(64),
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_rule_api_dimension ON rate_limit_rule (api_id, dimension);

-- Per-subject exceptions (VIP department, abusive IP, load-test account).
CREATE TABLE rate_limit_override (
    override_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id        BIGINT      NOT NULL REFERENCES rate_limit_rule(rule_id),
    dimension      VARCHAR(16) NOT NULL,
    subject_value  VARCHAR(128) NOT NULL,
    limit_count    INT,                           -- NULL = inherit from the rule
    window_seconds INT,
    blocked        BOOLEAN     NOT NULL DEFAULT FALSE,
    expires_at     TIMESTAMP WITH TIME ZONE,
    reason         VARCHAR(255),
    CONSTRAINT uq_override UNIQUE (rule_id, dimension, subject_value)
);

-- Which plan a department / employee / API key is on.
CREATE TABLE subject_plan (
    dimension     VARCHAR(16)  NOT NULL,
    subject_value VARCHAR(128) NOT NULL,
    plan_id       BIGINT       NOT NULL REFERENCES rate_limit_plan(plan_id),
    PRIMARY KEY (dimension, subject_value)
);

-- Denials, written asynchronously. Keep short retention; on PostgreSQL partition by day.
CREATE TABLE rate_limit_event (
    event_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    api_id        VARCHAR(64),
    rule_id       BIGINT,
    dimension     VARCHAR(16),
    subject_value VARCHAR(128),
    decision      VARCHAR(16) NOT NULL            -- DENIED | SHADOW_DENIED | BLOCKED | FAIL_CLOSED
);
CREATE INDEX idx_event_time ON rate_limit_event (occurred_at);
